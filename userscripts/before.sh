# Runs inside the builder after repo sync: add the verified prebuilt apps.
set -euo pipefail

src=/root/userscripts
out=vendor/extra-apps
# vendor/aurora is the location used by the 2026-10-14 build; a leftover copy
# would define AuroraStore twice.
rm -rf vendor/aurora "$out"
mkdir -p "$out"

while read -r module package code sha; do
    [[ -z "$module" || "$module" == \#* ]] && continue
    printf '%s  %s\n' "$sha" "$src/apps/$module.apk" | sha256sum --check --status
    mkdir -p "$out/$module"
    cp "$src/apps/$module.apk" "$out/$module/$module.apk"
    cat > "$out/$module/Android.bp" <<EOF
// Generated by userscripts/before.sh: $package, F-Droid version code $code
android_app_import {
    name: "$module",
    apk: "$module.apk",
    presigned: true,
    preprocessed: true,
    product_specific: true,
    dex_preopt: {
        enabled: false,
    },
}
EOF
done < "$src/apps.list"

# Leave out unwanted LineageOS packages (userscripts/removed-packages.list).
python3 - "$src/removed-packages.list" vendor/lineage/config/*.mk <<'PY'
import re, sys
names = {l.strip() for l in open(sys.argv[1]) if l.strip() and not l.startswith('#')}
found = set()
for path in sys.argv[2:]:
    lines = open(path).read().split('\n')
    out = []
    for line in lines:
        m = re.fullmatch(r'\s*(\S+)\s*(\\?)', line)
        if m and m.group(1) in names:
            found.add(m.group(1))
            if not m.group(2) and out and out[-1].rstrip().endswith('\\'):
                out[-1] = out[-1].rstrip()[:-1].rstrip()
            continue
        out.append(line)
    open(path, 'w').write('\n'.join(out))
missing = names - found
if missing:
    # Already removed by an earlier run on an unreset tree, or a typo in the list.
    print(f'Warning: not found in vendor/lineage/config: {sorted(missing)}')
PY

# Preconfigure the Tangelo OS app repository in F-Droid, next to microG's
# repositories. F-Droid reads the XML (older clients) and the JSON (current
# clients) from /product/etc/org.fdroid.fdroid/. begin.sh undoes this before
# the next sync.
python3 - "$src/fdroid-repos.json" vendor/partner_gms/additional_repos.xml <<'PY'
import json, sys
from pathlib import Path
from xml.sax.saxutils import escape
extra = json.load(open(sys.argv[1]))
base = Path(sys.argv[2])
js = base / 'additional_repos.json'
repos = [r for r in json.loads(js.read_text()) if r['address'] not in {e['address'] for e in extra}]
js.write_text(json.dumps(repos + extra, indent=2) + '\n')
xml = base / 'additional_repos.xml'
text = xml.read_text()
items = ''.join(
    f"\n        <item>{escape(r['name'])}</item>\n        <item>{escape(r['address'])}</item>"
    f"\n        <item>{escape(r['description'])}</item>\n        <item>19</item>"
    f"\n        <item>{1 if r['enabled'] else 0}</item>\n        <item>ignore</item>"
    f"\n        <item>{r['certificate']}</item>\n"
    for r in extra if r['address'] not in text)
xml.write_text(text.replace('    </string-array>', items + '    </string-array>', 1))
PY

# Tangelo OS overlays (branding, setup wizard texts) in vendor/tangelo.
rm -rf vendor/tangelo
cp -r "$src/vendor-tangelo" vendor/tangelo
printf '\n$(call inherit-product, vendor/tangelo/tangelo.mk)\n' >> vendor/lineage/config/common.mk

# LineageOS statistics: opt-in instead of a pre-ticked box in the setup wizard.
# begin.sh undoes this before the next sync.
python3 - packages/apps/SetupWizard/src/org/lineageos/setupwizard/LineageSettingsActivity.java <<'PY'
import sys
from pathlib import Path
p = Path(sys.argv[1])
old = '!myPageBundle.containsKey(KEY_SEND_METRICS) || myPageBundle'
new = 'myPageBundle.containsKey(KEY_SEND_METRICS) && myPageBundle'
text = p.read_text()
if new not in text:
    if text.count(old) != 1:
        sys.exit('SetupWizard: metrics default not found; check the opt-in patch')
    p.write_text(text.replace(old, new))
PY

# Tangelo OS boot animation in place of the LineageOS one.
cp "$src/bootanimation/bootanimation.tar" "$src/bootanimation/desc.txt" vendor/lineage/bootanimation/
